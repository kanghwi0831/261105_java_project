package day07;

public class Class01 {
	
	// ==> 메서드 선언 가능 위치
	// 두 정수를 받아(매개변수) 합을 리턴하는 메서드
	// 리턴타입 : 합 (정수) => int
	// 메서드명 : sum (내맘대로)
	// 매개변수 : 두 정수 (변수만 선언하듯이) => int a, int b
	public int sum(int a, int b) {
		return a + b;
	}
	
	// 두 정수를 입력받아(매개변수) 차를 리턴하는 메서드
	// 리턴타입 : 차 (정수) => int
	// 메서드명 : sub
	// 매개변수 : 두 정수 => int a, int b
	public int sub(int a, int b) {
		return a - b;
	}
	
	// 메서드 호출
	public static void main(String[] args) {
		int num1 = 10;
		int num2 = 20;
		
		// 같은 클래스 안의 메서드를 호출. 메서드명을 이용하여 호출
		// static : 일반 메서드 호출 불가 (static이 붙은 메서드만 호출가능)
		//    - 같은 클래스라도 객체를 생성해야 호출 가능
		// 같은 클래스라면 일반 메서드는 객체 생성없이 호출가능 (static 제외)
		// 다른 클래스라면 반드시 객체를 생성해야 가능
		
		// 객체생성 : 클래스명 객체명 = new 클래스명();
		Class01 c = new Class01();    // Class01에 변수명 c를 넣고 내가 만들어둔 메서드들을 사용하겠다
		// 객채명.메서드명(매개변수);
		int sum = c.sum(num1, num2);  // int sum = 내가 만든 변수명 c. 내가 만든 메서드 sum
		System.out.println(sum);
		
		int sub = c.sub(num1, num2);
		System.out.println(sub);
	}
	
	// 클래스 : 멤버변수(클래스가 가지는 요소), 메서드(해야하는 기능)
	// main method : 컴파일러가 실행을 위해 제일 먼저 찾는 메서드
	
	// 멤버변수의 위치 : (클래스 안 / 메서드 밖)
	// 메서드의 위치 : 멤버변수 다음 (무순서)  호출 => 실행
	
	// 메서드 구조
	// 접근제어자 *리턴타입 메서드명(매개변수) {
	// 구현};
	// return; 리턴이 있다면 가장 마지막에 붙음 // 있을 수도 있고 없을 수도 있다.
	// return의 변수명은 반드시 *리턴타입과 타입이 일치해야함.
	
	// 접근제어자 : 접근할 수 있는 주체의 제한범위
	// public (누구나 접근)
	// default (같은 패키지에 있는 클래스만 접근가능)
	// protected (같은패키지 + 상속)
	// private (나만 가능) - 멤버변수
	
	// 리턴타입 : 메서드가 종료되고난 후 (처리가 안료되고 난 후) 반환 값(반드시 1개)
	// - void : 리턴할 값이 없다.
	
	// 메서드명 : 소문(해도됨)로 시작(여러 의미를 붙여서 사용할 경우 카멜케이스를 사용
	// 매개변수 : 파라미터 (이 기능을 실행하기 위해 외부에서 받는 값
	//    - 여러개 있어도 가능, 한개만 있어도 가능
	//    - ()는 꼭 있어야함.
	
	// return : 메서드를 종료하는 키워드
	//    - 리턴타입과 일치하는 리턴값을 주고 종료
	//    - void는 없음.
	
	// 메서드는 중복 선언이 안됨.
	// 메서드 안에 또 다른 메서드가 있을 수 없다.
	// 메서드 단위로 위치는 상관없음
	// 메서드 선언 위치
	//    - 클래스 안, 다른 메서드 밖
	//    - 메서드는 독립적 운영
	//    - 순서는 상관없음
	//    - 호출되어야 실행
	
	
	
}
